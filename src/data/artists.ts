/**
 * Discover filters use these five broad lanes so the chips stay readable. Each
 * artist keeps their precise genre labels (shown on cards and artist pages);
 * lanesOf() maps those labels to the lanes.
 */
export const LANES = ["Electronic", "Hip-Hop & Rap", "R&B", "Pop", "Indie & Alternative"] as const;

const LANE_KEYWORDS: Record<(typeof LANES)[number], string[]> = {
  Electronic: ["electronic", "hyperpop", "jungle", "d&b", "house", "electro", "industrial"],
  "Hip-Hop & Rap": ["hip-hop", "rap", "rage", "jerk", "trap"],
  "R&B": ["r&b"],
  Pop: ["pop"],
  "Indie & Alternative": ["indie", "alternative", "alt-rock", "folk", "singer-songwriter", "grunge", "punk", "shoegaze", "cold wave", "art-rock", "art rock", "psych rock", "dream"],
};

export function lanesOf(genres: string[]): string[] {
  return LANES.filter((lane) => genres.some((g) => LANE_KEYWORDS[lane].some((k) => g.toLowerCase().replace("garage", "").includes(k))));
}

/** The scrolling "Now listening" ticker: whoever is currently published. */
export const TICKER_ARTISTS = ARTISTS.map((a) => a.name);
